<h2>0.8.0 · 2026 年 10 月 6 日</h2><ul>
<li>新功能：续传拷贝。在可读写的盘上点“拷贝到这块盘…”（也可以把文件直接拖进盘屿窗口），由盘屿来拷；中途断开、推出或退出盘屿后，盘重新连接并安全恢复可写时，会先核对已有内容再继续拷贝。</li>
